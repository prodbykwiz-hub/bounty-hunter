"""GitHub через gh CLI: работает от того аккаунта, под которым залогинен gh."""

from __future__ import annotations

import base64
import json
import logging
import re
import shutil
import subprocess
import time
from typing import Any

log = logging.getLogger("bounty_agent")

GH_TIMEOUT = 120
POLICY_FILES = ("AI_POLICY.md", "CONTRIBUTING.md", ".github/CONTRIBUTING.md", "docs/CONTRIBUTING.md")
AI_POLICY_RE = re.compile(
    r"[^.\n]*\b(?:ai[- ]generated|generated by ai|llms?|chatgpt|copilot|claude|gemini|"
    r"large language model|artificial intelligence|ai tools?|ai[- ]assisted)\b[^.\n]*",
    re.IGNORECASE,
)

ISSUE_QUERY = """
query($id: ID!) {
  node(id: $id) {
    ... on Issue {
      number title body url state createdAt
      author { login }
      repository { nameWithOwner defaultBranchRef { name } }
      assignees(first: 10) { nodes { login } }
      labels(first: 20) { nodes { name } }
      comments(last: 40) {
        nodes { databaseId body createdAt authorAssociation author { __typename login } }
      }
    }
  }
}
"""


class GhError(Exception):
    pass


class AccountMismatch(GhError):
    pass


class GitHub:
    def __init__(self, expected_user: str) -> None:
        if not shutil.which("gh"):
            raise GhError("gh CLI не найден в PATH")
        self.expected_user = expected_user

    def _gh(self, *args: str, payload: dict[str, Any] | None = None) -> str:
        proc = subprocess.run(
            ["gh", *args],
            input=json.dumps(payload) if payload is not None else None,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=GH_TIMEOUT,
        )
        if proc.returncode != 0:
            raise GhError(f"gh {' '.join(args[:3])}: {proc.stderr.strip()[:500]}")
        return proc.stdout

    def api(self, path: str, method: str = "GET", payload: dict[str, Any] | None = None) -> Any:
        args = ["api", path, "--method", method, "-H", "Accept: application/vnd.github+json"]
        if payload is not None:
            args += ["--input", "-"]
        out = self._gh(*args, payload=payload)
        return json.loads(out) if out.strip() else None

    def graphql(self, query: str, **variables: Any) -> dict[str, Any]:
        args = ["api", "graphql", "-f", f"query={query}"]
        for name, value in variables.items():
            args += ["-F" if isinstance(value, int) else "-f", f"{name}={value}"]
        return json.loads(self._gh(*args)).get("data") or {}

    def active_user(self) -> str:
        return self.api("user")["login"]

    def ensure_account(self) -> None:
        """Любая запись на GitHub — только от ожидаемого аккаунта."""
        user = self.active_user()
        if user.lower() != self.expected_user.lower():
            raise AccountMismatch(
                f"gh залогинен как {user}, а нужен {self.expected_user}. "
                f"Выполни: gh auth login, затем gh auth switch --user {self.expected_user}"
            )

    def issue(self, node_id: str) -> dict[str, Any] | None:
        node = self.graphql(ISSUE_QUERY, id=node_id).get("node")
        if not node or "number" not in node:
            return None
        return {
            "repo": node["repository"]["nameWithOwner"],
            "default_branch": (node["repository"].get("defaultBranchRef") or {}).get("name") or "main",
            "number": node["number"],
            "title": node["title"],
            "body": node.get("body") or "",
            "url": node["url"],
            "state": node["state"],
            "author": (node.get("author") or {}).get("login") or "",
            "assignees": [a["login"] for a in node["assignees"]["nodes"]],
            "labels": [label["name"] for label in node["labels"]["nodes"]],
            "comments": [
                {
                    "id": c["databaseId"],
                    "body": c.get("body") or "",
                    "created_at": c["createdAt"],
                    "association": c.get("authorAssociation") or "NONE",
                    "login": (c.get("author") or {}).get("login") or "",
                    "is_bot": (c.get("author") or {}).get("__typename") == "Bot",
                }
                for c in node["comments"]["nodes"]
            ],
        }

    def ai_policy(self, repo: str) -> str:
        """Фрагменты правил репозитория про AI; пустая строка, если ничего не нашлось."""
        snippets: list[str] = []
        for path in POLICY_FILES:
            try:
                data = self.api(f"repos/{repo}/contents/{path}")
            except GhError:
                continue
            if not isinstance(data, dict) or data.get("encoding") != "base64":
                continue
            text = base64.b64decode(data.get("content", "")).decode("utf-8", errors="replace")
            for match in AI_POLICY_RE.finditer(text):
                snippet = " ".join(match.group(0).split())
                if snippet and snippet not in snippets:
                    snippets.append(f"{path}: {snippet[:200]}")
        return "\n".join(snippets[:4])

    def post_comment(self, repo: str, number: int, body: str) -> dict[str, Any]:
        self.ensure_account()
        result = self.api(f"repos/{repo}/issues/{number}/comments", method="POST", payload={"body": body})
        return {"id": result["id"], "url": result["html_url"]}

    def noreply_email(self) -> str:
        # Публичные коммиты подписываем noreply-адресом, чтобы не светить личную почту.
        user = self.api("user")
        return f"{user['id']}+{user['login']}@users.noreply.github.com"

    def fork(self, repo: str) -> str:
        """Создаёт форк (или возвращает существующий) и ждёт, пока он станет доступен."""
        self.ensure_account()
        full_name = self.api(f"repos/{repo}/forks", method="POST", payload={"default_branch_only": True})["full_name"]
        for _ in range(12):
            try:
                self.api(f"repos/{full_name}")
                return full_name
            except GhError:
                time.sleep(5)
        raise GhError(f"форк {full_name} так и не стал доступен")

    def create_pr(self, repo: str, head: str, base: str, title: str, body: str) -> str:
        self.ensure_account()
        result = self.api(f"repos/{repo}/pulls", method="POST", payload={
            "title": title, "head": head, "base": base, "body": body, "maintainer_can_modify": True,
        })
        return result["html_url"]
